/**
 * Detección de duplicados por similitud de nombre (Levenshtein normalizado).
 * Umbral: similitud >= 0.85
 */
function levenshtein(a, b) {
  const m = a.length, n = b.length;
  const dp = Array.from({ length: m + 1 }, (_, i) => [i, ...Array(n).fill(0)]);
  for (let j = 0; j <= n; j++) dp[0][j] = j;
  for (let i = 1; i <= m; i++) {
    for (let j = 1; j <= n; j++) {
      dp[i][j] = a[i-1] === b[j-1]
        ? dp[i-1][j-1]
        : 1 + Math.min(dp[i-1][j], dp[i][j-1], dp[i-1][j-1]);
    }
  }
  return dp[m][n];
}

function normalize(str) {
  return (str || '')
    .toLowerCase()
    .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9\s]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function similitud(a, b) {
  const na = normalize(a), nb = normalize(b);
  if (!na || !nb) return 0;
  const dist = levenshtein(na, nb);
  return 1 - dist / Math.max(na.length, nb.length);
}

export function checkDuplicados(registros, nombre, excludeId = null, umbral = 0.85) {
  if (!nombre) return [];
  return registros
    .filter(r => r.id !== excludeId)
    .map(r => ({ ...r, similitud: similitud(r.name, nombre) }))
    .filter(r => r.similitud >= umbral)
    .sort((a, b) => b.similitud - a.similitud);
}